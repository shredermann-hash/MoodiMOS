# MoodiMOS—« Guess the Animal » in the robot: everything prepared on the Mac, robot plays autonomously.
# 
# The game engine is in the torso (`firmware/moodimos-torso/GuessGame.h`): same probabilities as the prototype (`guess_animal.py`). The head responds via the torso screen buttons (green thumb, red thumb, question mark); the robot reads pre-recorded phrases via the voice siwis system.
# 
# ---
# Commands:
# - `… to_robot.py table` → Generates `firmware/moodimos-torso/GuessData.h` from `animals.json`
# - `… to_robot.py voix [--voix 1]` → Creates phrases (Piper, voice siwis) in `~/MoodiMOS-IA/devine_robot` with complete edition moods (`HUMEURS`)
# - `… to_robot.py envoyer [port]` → Stores phrases in the torso’s flash memory via USB (command: `deposer`)
# 
# Run with: `~/MoodiMOS-IA/venv-cerveau/bin/python` (Piper installed). Piper is GPL-3.0—runs as a standalone program, never imported. Close all torso serial monitors first.

import argparse, glob, json, os, re, select, subprocess, sys, termios, time, wave

ICI = os.path.dirname(os.path.abspath(__file__))
RACINE = os.path.normpath(os.path.join(ICI, "..", ".."))
TABLEAU = os.path.join(ICI, "animals.json")
ENTETE = os.path.join(RACINE, "firmware", "moodimos-torso", "GuessData.h")
IA = os.environ.get("MOODIMOS_IA", os.path.expanduser("~/MoodiMOS-IA"))
PIPER = os.path.join(IA, "venv-cerveau", "bin", "piper")
VOIX = os.path.join(IA, "piper", "fr_FR-siwis-medium.onnx")
SORTIE = os.path.join(IA, "devine_robot")
FLASH_KO = 8600          # FAT partition of 9 MB from the torso, excluding its table and wear leveling.

# Fixed phrases: filename on robot → spoken text. Questions and animals follow (devine_q00…, devine_a00…), in order of animals.json.
FIXES = {
    "devine_intro": "Coucou ! Pense très fort à un animal, mais ne me dis pas lequel ! Je vais le deviner. "
                    "Pour me répondre, appuie sur les boutons : le pouce vert pour oui, le pouce rouge pour non, "
                    "et le point d'interrogation si tu ne sais pas.",
    "devine_go": "Tu as choisi ton animal ? On y va !",
    "devine_encore": "Oh ! Alors je réfléchis encore…",
    "devine_youpi": "Youpi ! J'ai deviné !",
    "devine_bravo": "Tu m'as battu ! Bravo, tu es trop forte !",
    "devine_rejoue": "On rejoue ?",
    "devine_bientot": "D'accord ! À bientôt !",
}
# Emotion phrases (off-field): spoken by the torso when stored in its flash (otherwise a scream).
HUMEURS = {
    "secoue": "Ne me secoue pas comme un prunier ! Je ne suis pas ton jouet !",   # anger rises (3rd push incident)
}
# Letters of the trait (screen) on the torso (dashboard) in uppercase (DashboardNeon.cpp), capital letters.
ECRAN = set(" '!,-./:?%+0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZÀÂÇÈÉÊÎÔÙÛ")


def charger():
    t = json.load(open(TABLEAU, encoding="utf-8"))
    questions = [(k, v if isinstance(v, dict) else {"texte": v}) for k, v in t["questions"].items()]
    return questions, t["animals"]


def phrases():
    questions, animals = charger()
    p = dict(FIXES)
    p.update(HUMEURS)
    for i, (_, q) in enumerate(questions):
        p["devine_q%02d" % i] = q["texte"]
    for i, a in enumerate(animals):
        p["devine_a%02d" % i] = "Je crois que c'est… {} ! J'ai trouvé ?".format(a["nom"])
    return p


def pour_ecran(texte):
    t = texte.upper().replace("Œ", "OE").replace("…", "...")
    manque = set(t) - ECRAN
    if manque:
        sys.exit('Characters missing from the screen font: ' + "".join(sorted(manque)) + ' in “' + texte + '”')
    return t


def c_texte(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def table():
    questions, animals = charger()
    cles = [k for k, _ in questions]
    if len(cles) > 64:
        sys.exit('Maximum 64 questions (64-bit masks)')
    lignes = [
        '// Guess the Animal table (complete edition), generated by extras/guess_animal/to_robot.py from',
        '// animals.json: do not edit manually. For each animal, stores yes and uncertain answer masks',
        '// (bit n = question n); all remaining answers are no. An inverse question expects no',
        '// for a yes in the table. Text is uppercase for the torso screen stroke font.',
        "#pragma once",
        "#include <stdint.h>",
        "",
        "namespace GuessData {",
        "",
        "struct Question { const char* text; bool inverse; };",
        "struct Animal { const char* name; uint64_t yes, maybe; };",
        "",
        "constexpr int QUESTIONS = %d, ANIMALS = %d;" % (len(questions), len(animals)),
        "",
        "constexpr Question QUESTION[QUESTIONS] = {",
    ]
    for k, q in questions:
        lignes.append("  {%s, %s},   // %s" % (c_texte(pour_ecran(q["texte"])), "true" if q.get("inverse") else "false", k))
    lignes += ["};", "", "constexpr Animal ANIMAL[ANIMALS] = {"]
    for a in animals:
        for k in a["oui"] + a["doute"]:
            if k not in cles:
                sys.exit('Unknown question “{}” for {}'.format(k, a["nom"]))
        oui = sum(1 << cles.index(k) for k in a["oui"])
        doute = sum(1 << cles.index(k) for k in a["doute"])
        lignes.append("  {%s, 0x%016xULL, 0x%016xULL}," % (c_texte(pour_ecran(a["nom"])), oui, doute))
    lignes += ["};", "", "}  // namespace GuessData", ""]
    open(ENTETE, "w", encoding="utf-8").write("\n".join(lignes))
    print("{} : {} questions, {} animals".format(os.path.relpath(ENTETE, RACINE), len(questions), len(animals)))


def voix(numero):
    sys.path.insert(0, os.path.join(RACINE, "brain"))
    from robot_voice import FILTRES, robotiser
    filtre = list(FILTRES.values())[numero - 1]
    os.makedirs(SORTIE, exist_ok=True)
    total = 0
    for nom, texte in phrases().items():
        brut, final = os.path.join(SORTIE, nom + ".brut.wav"), os.path.join(SORTIE, nom + ".wav")
        subprocess.run([PIPER, "-m", VOIX, "-f", brut], input=texte.encode(), check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        robotiser(brut, brut + ".robot.wav", filtre)
        # PCM 16-bit mono, 16 kHz audio from the torso, peak level at 70% (same as other phrases).
        subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", brut + ".robot.wav", "-af",
                        "loudnorm=I=-18:TP=-3,aresample=16000", "-ac", "1", "-ar", "16000", "-sample_fmt", "s16",
                        final], check=True)
        os.remove(brut)
        os.remove(brut + ".robot.wav")
        total += os.path.getsize(final)
        print("  {:<15} {}".format(nom, texte))
    print('{} phrases, {:.0f} KB for {} KB of flash storage in the torso.'.format(len(phrases()), total / 1024, FLASH_KO))
    if total / 1024 > FLASH_KO:
        sys.exit('Too large for the torso flash storage')


def ouvrir(port):
    fd = os.open(port, os.O_RDWR | os.O_NOCTTY | os.O_NONBLOCK)
    attr = termios.tcgetattr(fd)
    attr[0] = attr[1] = attr[3] = 0
    attr[2] = termios.CS8 | termios.CREAD | termios.CLOCAL
    attr[4] = attr[5] = termios.B115200
    termios.tcsetattr(fd, termios.TCSANOW, attr)
    time.sleep(0.2)
    termios.tcflush(fd, termios.TCIFLUSH)
    return fd


def attendre(fd, motif, delai):
    'Read until encountering `motif` (regex byte pattern); return all read content.'
    rep, fin = b"", time.time() + delai
    while not re.search(motif, rep) and time.time() < fin:
        if select.select([fd], [], [], 0.05)[0]:
            try:
                rep += os.read(fd, 4096)
            except BlockingIOError:
                pass
    return rep


def ecrire(fd, octets):
    vue = memoryview(octets)
    while vue:
        try:
            vue = vue[os.write(fd, vue):]
        except BlockingIOError:
            select.select([], [fd], [], 0.5)


def deposer(fd, nom, donnees):
    "Send 'deposer <name> <bytes>', then file data in 4 KB chunks, each acknowledged with '+'."
    ecrire(fd, b"deposer %s %d\n" % (nom.encode(), len(donnees)))
    rep = attendre(fd, rb"pret|refus", 30.0)          # First time, the torso initializes its partition.
    if b"pret" not in rep:
        return rep.decode("utf-8", "replace").strip() or 'No response'
    for k in range(0, len(donnees), 4096):
        ecrire(fd, donnees[k:k + 4096])
        if b"+" not in attendre(fd, rb"\+", 5.0):
            return 'No acknowledgement for chunk %d' % (k // 4096)
    rep = attendre(fd, rb"deposer[^\n]*\n", 5.0).decode("utf-8", "replace")
    somme = sum(donnees) & 0xFFFFFFFF
    return None if "somme %d" % somme in rep else rep.strip()


def envoyer(port):
    if not port:
        ports = sorted(glob.glob("/dev/cu.usbmodem*"))
        if not ports:
            sys.exit('Torso not found on USB')
        port = ports[0]
    noms = list(phrases())
    absents = [n for n in noms if not os.path.exists(os.path.join(SORTIE, n + ".wav"))]
    if absents:
        sys.exit('Generate the phrases first (… to_robot.py voix): ' + ", ".join(absents[:5]))
    fd = ouvrir(port)
    t0 = time.time()
    try:
        for i, nom in enumerate(noms):
            donnees = open(os.path.join(SORTIE, nom + ".wav"), "rb").read()
            for essai in range(3):   # Transient failures can occur when camera logs are mixed with replies.
                erreur = deposer(fd, nom, donnees)
                if not erreur:
                    break
                print('\n  {}: {}, retrying'.format(nom, erreur))
                time.sleep(3)        # the torso abandons reception (1 s without byte) and reads the remainder as binary data.
                termios.tcflush(fd, termios.TCIOFLUSH)   # unknown commands: wait until it has finished
            if erreur:
                sys.exit("{} : {}".format(nom, erreur))
            print("\r  {}/{} {}".format(i + 1, len(noms), nom).ljust(40), end="", flush=True)
    finally:
        os.close(fd)
    print('\n{} phrases stored in the torso in {:.0f} s.'.format(len(noms), time.time() - t0))


def main():
    ap = argparse.ArgumentParser(description='Guess the Animal: table and phrases for the robot')
    ap.add_argument("action", choices=["table", "voix", "envoyer"])
    ap.add_argument("port", nargs="?")
    ap.add_argument("--voix", type=int, default=1, help='Voice from brain/robot_voice.py (1 = siwis, default)')
    args = ap.parse_args()
    if args.action == "table":
        table()
    elif args.action == "voix":
        voix(args.voix)
    else:
        envoyer(args.port)


if __name__ == "__main__":
    main()
